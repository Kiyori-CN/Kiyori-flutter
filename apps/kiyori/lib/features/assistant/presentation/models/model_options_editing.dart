import 'package:kiyori_bridge/kiyori_bridge.dart';

/// 不改变核心默认值；编辑器每个区域只回填自己拥有的选项。
extension ModelOptionsEditing on ModelOptions {
  ModelOptions copyWith({
    double? contextLength,
    double? maxContextLength,
    bool? maxContextMode,
    bool? summaryEnabled,
    double? summaryThreshold,
    bool? summaryByCount,
    int? summaryCount,
    String? summaryRules,
    bool? image,
    bool? audio,
    bool? video,
    bool? googleSearch,
    bool? claudeCache,
    bool? toolCall,
    int? requestLimit,
    int? concurrentLimit,
    int? mnnForward,
    int? mnnThreads,
    int? llamaThreads,
    int? llamaContext,
    int? llamaBatch,
    int? llamaMicroBatch,
    int? llamaGpuLayers,
    bool? llamaMmap,
    bool? llamaFlashAttention,
    bool? llamaKvUnified,
    bool? llamaOffloadKqv,
    List<ModelParameter>? parameters,
  }) => ModelOptions(
    contextLength: contextLength ?? this.contextLength,
    maxContextLength: maxContextLength ?? this.maxContextLength,
    maxContextMode: maxContextMode ?? this.maxContextMode,
    summaryEnabled: summaryEnabled ?? this.summaryEnabled,
    summaryThreshold: summaryThreshold ?? this.summaryThreshold,
    summaryByCount: summaryByCount ?? this.summaryByCount,
    summaryCount: summaryCount ?? this.summaryCount,
    summaryRules: summaryRules ?? this.summaryRules,
    image: image ?? this.image,
    audio: audio ?? this.audio,
    video: video ?? this.video,
    googleSearch: googleSearch ?? this.googleSearch,
    claudeCache: claudeCache ?? this.claudeCache,
    toolCall: toolCall ?? this.toolCall,
    requestLimit: requestLimit ?? this.requestLimit,
    concurrentLimit: concurrentLimit ?? this.concurrentLimit,
    mnnForward: mnnForward ?? this.mnnForward,
    mnnThreads: mnnThreads ?? this.mnnThreads,
    llamaThreads: llamaThreads ?? this.llamaThreads,
    llamaContext: llamaContext ?? this.llamaContext,
    llamaBatch: llamaBatch ?? this.llamaBatch,
    llamaMicroBatch: llamaMicroBatch ?? this.llamaMicroBatch,
    llamaGpuLayers: llamaGpuLayers ?? this.llamaGpuLayers,
    llamaMmap: llamaMmap ?? this.llamaMmap,
    llamaFlashAttention: llamaFlashAttention ?? this.llamaFlashAttention,
    llamaKvUnified: llamaKvUnified ?? this.llamaKvUnified,
    llamaOffloadKqv: llamaOffloadKqv ?? this.llamaOffloadKqv,
    parameters: parameters ?? this.parameters,
  );

  Map<String, Object> get comparison => {
    'contextLength': contextLength,
    'maxContextLength': maxContextLength,
    'maxContextMode': maxContextMode,
    'summaryEnabled': summaryEnabled,
    'summaryThreshold': summaryThreshold,
    'summaryByCount': summaryByCount,
    'summaryCount': summaryCount,
    'summaryRules': summaryRules,
    'image': image,
    'audio': audio,
    'video': video,
    'googleSearch': googleSearch,
    'claudeCache': claudeCache,
    'toolCall': toolCall,
    'requestLimit': requestLimit,
    'concurrentLimit': concurrentLimit,
    'mnnForward': mnnForward,
    'mnnThreads': mnnThreads,
    'llamaThreads': llamaThreads,
    'llamaContext': llamaContext,
    'llamaBatch': llamaBatch,
    'llamaMicroBatch': llamaMicroBatch,
    'llamaGpuLayers': llamaGpuLayers,
    'llamaMmap': llamaMmap,
    'llamaFlashAttention': llamaFlashAttention,
    'llamaKvUnified': llamaKvUnified,
    'llamaOffloadKqv': llamaOffloadKqv,
    'parameters': parameters
        .map((p) => [p.name, p.enabled, p.valueType, p.value, p.category])
        .toList(),
  };
}
